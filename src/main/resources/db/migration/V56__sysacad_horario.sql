CREATE TABLE sysacad_horario (
    id_horario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio integer NOT NULL,
    especialidad integer NOT NULL,
    plan integer NOT NULL,
    materia integer NOT NULL,
    comision integer NOT NULL,
    dia integer NOT NULL,
    cuatrimestre integer NOT NULL,
    curso character varying(255),
    hora_comienzo time without time zone,
    hora_fin time without time zone,
    duracion integer,
    edificio_conocido integer,
    aula_conocida integer,
    presente_en_vista boolean DEFAULT true NOT NULL,
    ultima_lectura timestamp with time zone,
    edificio_base integer,
    aula_base integer,
    id_evento_1 bigint,
    id_evento_2 bigint,
    enviable boolean DEFAULT true NOT NULL,
    motivo_no_enviable character varying(40),
    edificio_diferente integer,
    aula_diferente integer,
    diferencia_detectada_en timestamp with time zone,
    estado character varying(20) DEFAULT 'SYNCED' NOT NULL,
    edificio_en_envio integer,
    aula_en_envio integer,
    intentos integer DEFAULT 0 NOT NULL,
    proximo_intento timestamp with time zone,
    ultimo_error character varying(1000),
    motivo_revision character varying(40),
    revision_desde timestamp with time zone,
    version bigint DEFAULT 0 NOT NULL,
    creado_en timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actualizado_en timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_sysacad_horario_clave
        UNIQUE (anio, especialidad, plan, materia, comision, dia, cuatrimestre),
    CONSTRAINT chk_sysacad_horario_estado
        CHECK (estado IN ('SYNCED', 'PENDING', 'SENDING', 'WAITING', 'REVIEW')),
    CONSTRAINT chk_sysacad_horario_cuatrimestre CHECK (cuatrimestre IN (0, 1, 2)),
    CONSTRAINT chk_sysacad_horario_dia CHECK (dia BETWEEN 1 AND 7)
);

ALTER TABLE sysacad_horario ADD CONSTRAINT fk_sysacad_horario_evento_1
    FOREIGN KEY (id_evento_1) REFERENCES evento_recurrente (id_evento_academico) NOT VALID;
ALTER TABLE sysacad_horario ADD CONSTRAINT fk_sysacad_horario_evento_2
    FOREIGN KEY (id_evento_2) REFERENCES evento_recurrente (id_evento_academico) NOT VALID;

CREATE INDEX idx_sysacad_horario_evento_1 ON sysacad_horario (id_evento_1) WHERE id_evento_1 IS NOT NULL;
CREATE INDEX idx_sysacad_horario_evento_2 ON sysacad_horario (id_evento_2) WHERE id_evento_2 IS NOT NULL;
