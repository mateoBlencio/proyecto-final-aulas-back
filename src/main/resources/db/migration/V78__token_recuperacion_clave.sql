CREATE TABLE token_recuperacion_clave (
    id_token_recuperacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            bigint       NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    token_hash            varchar(255) NOT NULL,
    fecha_creacion        timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion      timestamp    NOT NULL,
    fecha_uso             timestamp,
    CONSTRAINT uq_token_recuperacion_hash UNIQUE (token_hash)
);

CREATE INDEX idx_token_recuperacion_usuario ON token_recuperacion_clave (id_usuario);
