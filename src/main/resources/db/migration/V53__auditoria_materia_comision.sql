DROP SEQUENCE IF EXISTS materia_comision_id_materia_comision_seq;
ALTER TABLE materia_comision DROP CONSTRAINT materia_comision_pkey;
ALTER TABLE materia_comision ADD COLUMN id_materia_comision bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
ALTER TABLE materia_comision ADD CONSTRAINT uq_materia_comision UNIQUE (id_materia, id_comision);

CREATE TABLE materia_comision_aud (
    id_materia_comision bigint NOT NULL,
    rev integer NOT NULL REFERENCES revinfo (rev),
    revtype smallint,
    id_materia bigint,
    id_comision bigint,
    es_presencial boolean,
    eliminado_en timestamp,
    motivo_baja varchar(40),
    PRIMARY KEY (id_materia_comision, rev)
);
CREATE INDEX idx_materia_comision_aud_rev ON materia_comision_aud (rev);

DO $$
DECLARE
    v_rev integer;
    v_id text;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.materia_comision) THEN
        RETURN;
    END IF;

    INSERT INTO public.revinfo (fecha_revision, usuario, tipo_actor, descripcion, operacion_id, usuario_bd)
    VALUES (clock_timestamp() AT TIME ZONE 'America/Argentina/Buenos_Aires', NULL, 'HUMAN',
            'Corrección manual: Estado inicial de materia-comisión', gen_random_uuid()::text, left(session_user::text, 63))
    RETURNING rev INTO v_rev;

    FOR v_id IN SELECT id_materia_comision::text FROM public.materia_comision ORDER BY id_materia_comision LOOP
        PERFORM public.auditoria_registrar(v_rev, 'materia_comision_aud', v_id, 0);
    END LOOP;

    UPDATE public.revinfo SET tipo_actor = 'SYSTEM', descripcion = 'Estado inicial de materia-comisión' WHERE rev = v_rev;
END
$$;
