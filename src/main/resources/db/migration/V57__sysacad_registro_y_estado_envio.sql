-- Registro de solo agregado: los roles con privilegios sobre la tabla (menos el dueño) pierden UPDATE y DELETE.
-- Con relacl nulo (tabla solo del dueño, como en Testcontainers) el bucle no corre.
DO $$
DECLARE
    r record;
BEGIN
    FOR r IN
        SELECT DISTINCT g.rolname
          FROM pg_class c
         CROSS JOIN LATERAL aclexplode(c.relacl) a
          JOIN pg_roles g ON g.oid = a.grantee
         WHERE c.oid = 'public.sysacad_horario_registro'::regclass
           AND a.grantee <> c.relowner
    LOOP
        EXECUTE format('REVOKE UPDATE, DELETE ON public.sysacad_horario_registro FROM %I', r.rolname);
    END LOOP;
END
$$;
