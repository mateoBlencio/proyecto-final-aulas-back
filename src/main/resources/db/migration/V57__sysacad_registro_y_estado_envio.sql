CREATE TABLE sysacad_horario_registro (
    id_registro bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_horario bigint NOT NULL REFERENCES sysacad_horario (id_horario),
    fecha timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    tipo character varying(40) NOT NULL,
    resultado character varying(40),
    motivo character varying(255),
    edificio_anterior integer,
    aula_anterior integer,
    edificio_nuevo integer,
    aula_nuevo integer,
    hora_enviada time without time zone,
    duracion_enviada integer,
    hora_leida time without time zone,
    duracion_leida integer,
    hora_fin_leida time without time zone,
    hora_releida time without time zone,
    duracion_releida integer,
    hora_fin_releida time without time zone,
    intentos integer,
    error_id character varying(100),
    respuesta text,
    ocurrencias jsonb,
    id_ocurrencia bigint,
    id_item bigint,
    usuario_revision character varying(150),
    operacion_revision character varying(100),
    resuelto_por character varying(150)
);

CREATE INDEX idx_sysacad_horario_registro_horario_fecha ON sysacad_horario_registro (id_horario, fecha DESC);

CREATE TABLE sysacad_envio_estado (
    id smallint PRIMARY KEY CHECK (id = 1),
    ultima_corrida_inicio timestamp with time zone,
    ultima_corrida_fin timestamp with time zone,
    ultimo_resultado character varying(40),
    ultima_lectura_vista timestamp with time zone,
    caida_desde timestamp with time zone,
    ultimo_aviso_caida timestamp with time zone,
    pausado_hasta timestamp with time zone,
    ultimo_error character varying(1000)
);

