-- Monthly dashboard snapshot. One row per active building plus one campus row (id_edificio NULL).
-- Immutable: a regeneration marks the previous rows vigente = false and inserts new ones.
-- No FK to edificio: the snapshot outlives building changes.
CREATE TABLE tablero_snapshot (
    id_snapshot bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio integer NOT NULL,
    mes integer NOT NULL CHECK (mes BETWEEN 1 AND 12),
    id_edificio bigint,
    vigente boolean NOT NULL DEFAULT TRUE,
    version_esquema integer NOT NULL,
    version_reglas integer NOT NULL,
    generado_en timestamp(6) with time zone NOT NULL,
    generado_por varchar(150) NOT NULL,
    motivo_regeneracion varchar(500),
    datos jsonb NOT NULL
);
CREATE UNIQUE INDEX uq_tablero_snapshot_vigente
    ON tablero_snapshot (anio, mes, COALESCE(id_edificio, 0)) WHERE vigente;
CREATE INDEX idx_tablero_snapshot_anio_mes ON tablero_snapshot (anio, mes);
