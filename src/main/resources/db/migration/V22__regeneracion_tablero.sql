-- One row per manual regeneration of a dashboard month. Audited by Envers: snapshot rows are not.
CREATE TABLE regeneracion_tablero (
    id_regeneracion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio integer NOT NULL,
    mes integer NOT NULL,
    motivo varchar(500) NOT NULL,
    regenerado_en timestamp(6) with time zone NOT NULL
);
CREATE TABLE regeneracion_tablero_aud (
    id_regeneracion bigint NOT NULL,
    rev integer NOT NULL REFERENCES revinfo (rev),
    revtype smallint,
    anio integer,
    mes integer,
    motivo varchar(500),
    regenerado_en timestamp(6) with time zone,
    PRIMARY KEY (id_regeneracion, rev)
);
CREATE INDEX idx_regeneracion_tablero_aud_rev ON regeneracion_tablero_aud (rev);
